export function AdminLocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<AdminLocale>('zh')

  useEffect(() => {
    const saved = localStorage.getItem('admin-locale') as AdminLocale | null
    if (saved && (saved === 'zh' || saved === 'en')) {
      setLocaleState(saved)
    }
  }, [])

  const setLocale = (l: AdminLocale) => {
    setLocaleState(l)
    localStorage.setItem('admin-locale', l)
  }

  const t = (key: string) => translations[locale][key] || key

  return (
    <AdminLocaleContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </AdminLocaleContext.Provider>
  )
}

export function useAdminLocale() {
  return useContext(AdminLocaleContext)
}
